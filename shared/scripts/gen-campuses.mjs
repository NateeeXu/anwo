// Regenerates shared/src/campuses.ts from docs/data/campuses.json.
// Usage: node shared/scripts/gen-campuses.mjs   (run from repo root or anywhere)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../docs/data/campuses.json');
const out = resolve(here, '../src/campuses.ts');
const raw = JSON.parse(readFileSync(src, 'utf8'));

const rows = raw.map((c, i) => ({
  id: c.id,
  slug: c.id,
  name: c.name,
  nameZh: c.nameZh ?? null,
  shortName: c.shortName,
  city: c.city,
  state: c.state,
  lat: c.lat,
  lng: c.lng,
  timezone: c.timezone,
  eduDomains: c.eduDomains ?? [],
  hasShuttle: !!c.hasShuttle,
  shuttleTrackerUrl: c.shuttleTrackerUrl ?? null,
  metro: c.metro ?? null,
  defaultRadiusM: 3000,
  intlStudents: c.intlStudentsApprox ?? null,
  sortOrder: i,
}));

const ids = new Set();
for (const r of rows) {
  if (ids.has(r.id)) throw new Error('duplicate campus id ' + r.id);
  ids.add(r.id);
}

const body = rows.map((r) => '  ' + JSON.stringify(r)).join(',\n');
const ts = `// AUTO-GENERATED by shared/scripts/gen-campuses.mjs from docs/data/campuses.json — do not edit by hand.
// ${rows.length} US campuses. Northwestern is first (launch campus); otherwise order carries no meaning.
import type { Campus } from './types';

export const CAMPUSES: Campus[] = [
${body}
];

export const CAMPUS_BY_ID: Record<string, Campus> = Object.fromEntries(CAMPUSES.map((c) => [c.id, c]));

export function findCampus(idOrSlug: string): Campus | undefined {
  return CAMPUSES.find((c) => c.id === idOrSlug || c.slug === idOrSlug);
}

/** Returns the campus whose edu domain matches the email's domain (suffix match), or undefined. */
export function campusForEmail(email: string): Campus | undefined {
  const domain = email.toLowerCase().split('@')[1] ?? '';
  if (!domain) return undefined;
  let best: Campus | undefined;
  let bestLen = 0;
  for (const c of CAMPUSES) {
    for (const d of c.eduDomains) {
      const dd = d.toLowerCase();
      if ((domain === dd || domain.endsWith('.' + dd)) && dd.length > bestLen) {
        best = c;
        bestLen = dd.length;
      }
    }
  }
  return best;
}

/** True when the email is an academic address: matches a campus domain or ends with .edu */
export function isEduEmail(email: string): boolean {
  const domain = email.toLowerCase().split('@')[1] ?? '';
  return !!campusForEmail(email) || domain === 'edu' || domain.endsWith('.edu');
}
`;
writeFileSync(out, ts);
console.log('wrote', out, rows.length, 'campuses');
