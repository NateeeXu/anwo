CREATE INDEX IF NOT EXISTS idx_conversations_context ON conversations(context_type, context_id);
CREATE INDEX IF NOT EXISTS idx_conversations_last_message ON conversations(last_message_at DESC);

CREATE TABLE IF NOT EXISTS conversation_members (
  conversation_id      TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  user_id              TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role                 TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('owner','admin','member')),
  joined_at            TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  left_at              TEXT,                             -- NULL = active member
  muted_until          TEXT,
  archived             INTEGER NOT NULL DEFAULT 0 CHECK (archived IN (0,1)),
  last_read_message_id TEXT,
  last_read_at         TEXT,
  unread_count         INTEGER NOT NULL DEFAULT 0,       -- trigger: +1 per message from others; app resets on chat.read
  scam_banner_dismissed INTEGER NOT NULL DEFAULT 0 CHECK (scam_banner_dismissed IN (0,1)),
  PRIMARY KEY (conversation_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_conversation_members_user ON conversation_members(user_id, archived, left_at);

CREATE TABLE IF NOT EXISTS messages (
  id              TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  sender_id       TEXT REFERENCES users(id) ON DELETE SET NULL,   -- NULL for kind='system'
  kind            TEXT NOT NULL DEFAULT 'text' CHECK (kind IN ('text','image','system','context_card')),
  body            TEXT,                                            -- text; system: i18n key or rendered text
  upload_id       TEXT REFERENCES uploads(id) ON DELETE SET NULL,  -- image kind
  context_json    TEXT CHECK (context_json IS NULL OR json_valid(context_json)),
                   -- context_card: {"type":"listing","id":"...","title":"...","priceCents":..,"coverUrl":..,"campusId":..}
