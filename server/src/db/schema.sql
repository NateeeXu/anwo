CREATE TABLE IF NOT EXISTS conversations (
  id               TEXT PRIMARY KEY,
  kind             TEXT NOT NULL DEFAULT 'direct' CHECK (kind IN ('direct','group','support')),
  title            TEXT,                                 -- groups only
  campus_id        TEXT REFERENCES campuses(id) ON DELETE SET NULL,
  context_type     TEXT CHECK (context_type IN ('listing','wanted','market_item','buddy_post','escrow')),
  context_id       TEXT,                                 -- id in the context table (no FK: polymorphic)
  created_by       TEXT REFERENCES users(id) ON DELETE SET NULL,
  direct_key       TEXT UNIQUE,                          -- direct only: sorted 'userA|userB|context_type|context_id' to dedupe
  last_message_id  TEXT,                                 -- trigger-maintained (no FK to avoid cycle)
  last_message_at  TEXT,
  last_message_preview TEXT,
  message_count    INTEGER NOT NULL DEFAULT 0,
  is_locked        INTEGER NOT NULL DEFAULT 0 CHECK (is_locked IN (0,1)),  -- admin-locked after moderation
  created_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
