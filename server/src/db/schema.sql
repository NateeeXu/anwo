CREATE TRIGGER IF NOT EXISTS trg_matches_upd AFTER UPDATE OF score ON matches
WHEN (OLD.score >= 50) <> (NEW.score >= 50) BEGIN
  UPDATE wanted_posts
     SET match_count = MAX(match_count + (CASE WHEN NEW.score >= 50 THEN 1 ELSE -1 END), 0)
   WHERE id = NEW.wanted_id;
END;

-- messages: bump conversation summary + unread counts for other active members
CREATE TRIGGER IF NOT EXISTS trg_messages_ins AFTER INSERT ON messages BEGIN
  UPDATE conversations
     SET last_message_id = NEW.id,
         last_message_at = NEW.created_at,
         last_message_preview = CASE NEW.kind
                                  WHEN 'text' THEN substr(COALESCE(NEW.body,''), 1, 120)
                                  WHEN 'image' THEN '[image]'
                                  WHEN 'context_card' THEN '[card]'
                                  ELSE substr(COALESCE(NEW.body,''), 1, 120) END,
         message_count = message_count + 1,
         updated_at = NEW.created_at
   WHERE id = NEW.conversation_id;
  UPDATE conversation_members
     SET unread_count = unread_count + 1
   WHERE conversation_id = NEW.conversation_id
     AND left_at IS NULL
     AND (NEW.sender_id IS NULL OR user_id <> NEW.sender_id);
END;

