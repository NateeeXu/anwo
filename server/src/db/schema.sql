CREATE TABLE IF NOT EXISTS shuttle_stops (
  id          TEXT PRIMARY KEY,
  campus_id   TEXT NOT NULL REFERENCES campuses(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  name_zh     TEXT,
  code        TEXT,                         -- short code if campus has one
  lat         REAL NOT NULL,
  lng         REAL NOT NULL,
  address     TEXT,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_shuttle_stops_campus ON shuttle_stops(campus_id, is_active);
CREATE INDEX IF NOT EXISTS idx_shuttle_stops_latlng ON shuttle_stops(lat, lng);

CREATE TABLE IF NOT EXISTS shuttle_route_stops (
  route_id            TEXT NOT NULL REFERENCES shuttle_routes(id) ON DELETE CASCADE,
  stop_id             TEXT NOT NULL REFERENCES shuttle_stops(id) ON DELETE CASCADE,
  sequence            INTEGER NOT NULL,     -- 0-based order along the route
  minutes_from_start  INTEGER NOT NULL DEFAULT 0,  -- travel offset from first stop
  PRIMARY KEY (route_id, stop_id),
  UNIQUE (route_id, sequence)
);
CREATE INDEX IF NOT EXISTS idx_shuttle_route_stops_stop ON shuttle_route_stops(stop_id);

-- Timetable entries: one row per scheduled departure at a stop.
-- "Next departures" = WHERE stop_id=? AND service_day=? AND departure_time >= ? ORDER BY departure_time LIMIT n
CREATE TABLE IF NOT EXISTS shuttle_schedule (
  id              TEXT PRIMARY KEY,
  route_id        TEXT NOT NULL REFERENCES shuttle_routes(id) ON DELETE CASCADE,
  stop_id         TEXT NOT NULL REFERENCES shuttle_stops(id) ON DELETE CASCADE,
  service_day     TEXT NOT NULL CHECK (service_day IN ('weekday','saturday','sunday','holiday')),
  departure_time  TEXT NOT NULL,            -- 'HH:MM' local campus time; may exceed '24:00' as '25:10' for after-midnight
  trip_index      INTEGER,                  -- groups departures belonging to one bus run
  valid_from      TEXT,                     -- 'YYYY-MM-DD' NULL = always
  valid_to        TEXT,
  created_at      TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_shuttle_schedule_stop_day_time ON shuttle_schedule(stop_id, service_day, departure_time);
CREATE INDEX IF NOT EXISTS idx_shuttle_schedule_route_day ON shuttle_schedule(route_id, service_day, departure_time);

CREATE TABLE IF NOT EXISTS shuttle_alerts (
  id          TEXT PRIMARY KEY,
  campus_id   TEXT NOT NULL REFERENCES campuses(id) ON DELETE CASCADE,
  route_id    TEXT REFERENCES shuttle_routes(id) ON DELETE CASCADE,  -- NULL = campus-wide
  severity    TEXT NOT NULL DEFAULT 'info' CHECK (severity IN ('info','warning','critical')),
  title       TEXT NOT NULL,
  title_zh    TEXT,
  body        TEXT,
  body_zh     TEXT,
  starts_at   TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  ends_at     TEXT,                         -- NULL = until removed
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_by  TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_shuttle_alerts_campus_active ON shuttle_alerts(campus_id, is_active, starts_at);

