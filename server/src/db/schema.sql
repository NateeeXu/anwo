  client_id       TEXT,                                            -- client-generated idempotency key
  reply_to_id     TEXT REFERENCES messages(id) ON DELETE SET NULL,
  edited_at       TEXT,
  deleted_at      TEXT,
  created_at      TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_messages_conversation_created ON messages(conversation_id, created_at);
CREATE INDEX IF NOT EXISTS idx_messages_sender ON messages(sender_id, created_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_messages_client_id ON messages(conversation_id, sender_id, client_id) WHERE client_id IS NOT NULL;

-- Per-message read receipts (group chats need per-user; direct chats could
-- rely on conversation_members.last_read_* alone but we keep both).
CREATE TABLE IF NOT EXISTS message_reads (
