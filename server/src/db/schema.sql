-- =====================================================================
--  campus-sublet — COMPLETE SQLite schema
--  File: server/src/db/schema.sql
--  Owner: architect. Module agents add ONLY additive migrations in
--  server/src/db/migrations/NN_<module>.sql (new tables / new columns /
--  new indexes). Never edit this file after the scaffold stage.
-- =====================================================================
--
--  CONVENTIONS (read before writing any query)
--  ---------------------------------------------------------------------
--  * Engine: node:sqlite (SQLite >= 3.45). The app runs, on every
--    connection, BEFORE this file:  PRAGMA foreign_keys = ON;
--    PRAGMA journal_mode = WAL;  PRAGMA busy_timeout = 5000;
--    This file must therefore contain no PRAGMA statements.
--  * This file is idempotent: every statement is CREATE ... IF NOT EXISTS.
--    It is executed with db.exec() on boot, then migrations/NN_*.sql in
--    numeric order (each tracked in `schema_migrations`), then seeds.
--  * IDs:         TEXT, crypto.randomUUID() generated by the app.
--  * Timestamps:  TEXT ISO-8601 UTC with millis, e.g. 2026-11-03T14:05:09.123Z.
--                 Column names end in _at. Default = now via strftime.
--  * Dates (no time): TEXT 'YYYY-MM-DD' ; column names end in _date / _on.
--  * Times of day:    TEXT 'HH:MM' 24h local campus time.
--  * Money:       INTEGER cents USD, column names end in _cents. Fees in
--                 basis points end in _bps (300 = 3.00%).
--  * Booleans:    INTEGER 0/1 with CHECK (x IN (0,1)). Names read as
--                 predicates: is_*, has_*, banned, boosted, etc.
--  * Enums:       TEXT with CHECK (col IN (...)). The authoritative list of
--                 enum values is docs/DATA_MODEL.md and shared/src/enums.ts;
--                 /api/meta exposes them to the web.
--  * JSON:        TEXT with CHECK (json_valid(col)). Column names end in
--                 _json. Default '[]' or '{}'.
--  * Coordinates: lat / lng REAL (WGS84). Radius search = bounding box on
--                 indexed lat/lng, then haversine in SQL (docs/DATA_MODEL.md §9).
--  * Soft delete: deleted_at TEXT NULL where a module needs it; otherwise
--                 rows use a status enum ('removed').
--  * Campus scope: every user-facing entity carries campus_id. List APIs
--                 filter by campus_id unless scope=nationwide.
--  * Counters:    denormalized *_count columns are maintained by the
--                 triggers at the bottom of this file. DO NOT also
--                 increment them in application code.
--  * Naming:      snake_case tables/columns, singular FK columns
--                 (<entity>_id), plural table names. Indexes are named
--                 idx_<table>_<cols>. Unique constraints via UNIQUE(...).
--  * ON DELETE:   CASCADE for owned children (photos, members, reads).
--                 SET NULL for references that must survive deletion
--                 (reviewer, upload references, campus on users).
--                 RESTRICT (default) for money rows (orders, payments,
--                 escrows, ledger) — these are never deleted, only
--                 status-changed.
-- =====================================================================

CREATE TABLE IF NOT EXISTS schema_migrations (
  name        TEXT PRIMARY KEY,              -- e.g. '10_listings.sql'
  applied_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);

-- =====================================================================
-- 1. CAMPUSES
-- =====================================================================
CREATE TABLE IF NOT EXISTS campuses (
  id               TEXT PRIMARY KEY,         -- stable slug-ish uuid, e.g. 'northwestern'
  name             TEXT NOT NULL,            -- 'Northwestern University'
  name_zh          TEXT,                     -- '西北大学'
  short_name       TEXT NOT NULL,            -- 'Northwestern' / 'NU'
  slug             TEXT NOT NULL UNIQUE,     -- 'northwestern' (used in URLs)
  city             TEXT NOT NULL,            -- 'Evanston'
  state            TEXT NOT NULL,            -- 'IL' (2-letter)
  country          TEXT NOT NULL DEFAULT 'US',
  lat              REAL NOT NULL,
  lng              REAL NOT NULL,
  timezone         TEXT NOT NULL,            -- IANA, 'America/Chicago'
  edu_domains_json TEXT NOT NULL DEFAULT '[]' CHECK (json_valid(edu_domains_json)), -- ["northwestern.edu","u.northwestern.edu"]
  has_shuttle      INTEGER NOT NULL DEFAULT 0 CHECK (has_shuttle IN (0,1)),
  shuttle_official_url TEXT,
  default_radius_m INTEGER NOT NULL DEFAULT 5000,  -- default search radius around campus
  intl_students    INTEGER,                  -- approx count, for sorting campus picker
  is_active        INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  sort_order       INTEGER NOT NULL DEFAULT 0,
  created_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_campuses_state_city ON campuses(state, city);
CREATE INDEX IF NOT EXISTS idx_campuses_latlng ON campuses(lat, lng);
CREATE INDEX IF NOT EXISTS idx_campuses_active_sort ON campuses(is_active, sort_order);

