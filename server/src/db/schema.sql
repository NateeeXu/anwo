-- =====================================================================
-- 14. VIEWS (read-only conveniences; admin dashboard uses these)
-- =====================================================================
-- Revenue is recognised when an order is PAID (by card or by wallet), never
-- when the wallet is topped up (a topup is a liability until it is spent).
-- Therefore wallet_topup orders are excluded, and wallet credit applied to an
-- order counts toward that order's revenue. Escrow: only the fee is revenue.
CREATE VIEW IF NOT EXISTS v_revenue AS
  SELECT p.id            AS payment_id,
         p.order_id,
         o.user_id,
         o.campus_id,
         o.kind          AS order_kind,
         CASE o.kind
           WHEN 'escrow_deposit' THEN o.fee_cents
           ELSE o.total_cents + o.credit_cents
         END             AS revenue_cents,
         p.amount_cents  AS gross_cents,         -- what the card was charged (0 for wallet-only orders)
         o.credit_cents  AS wallet_cents,        -- part of revenue_cents paid from wallet credit
         p.refunded_cents,
         p.succeeded_at  AS at
  FROM payments p JOIN orders o ON o.id = p.order_id
  WHERE p.status IN ('succeeded','partially_refunded')
    AND o.kind <> 'wallet_topup';

CREATE VIEW IF NOT EXISTS v_active_boosts AS
  SELECT * FROM boosts
  WHERE status = 'active'
    AND starts_at <= strftime('%Y-%m-%dT%H:%M:%fZ','now')
    AND ends_at   >  strftime('%Y-%m-%dT%H:%M:%fZ','now');

