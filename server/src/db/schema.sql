-- with zero areas means "anywhere within campus default radius" (campus scope)
-- or "anywhere in the US" (nationwide scope).
CREATE TABLE IF NOT EXISTS wanted_areas (
  id          TEXT PRIMARY KEY,
  wanted_id   TEXT NOT NULL REFERENCES wanted_posts(id) ON DELETE CASCADE,
  label       TEXT NOT NULL,                 -- 'Near Davis St', 'Downtown Evanston', 'Chicago, IL'
  kind        TEXT NOT NULL DEFAULT 'circle' CHECK (kind IN ('circle','city','campus')),
  lat         REAL,
  lng         REAL,
  radius_m    INTEGER,
  city        TEXT,
  state       TEXT,
  campus_id   TEXT REFERENCES campuses(id) ON DELETE SET NULL,
  sort_order  INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_wanted_areas_wanted ON wanted_areas(wanted_id);

-- Score cache wanted <-> listing. Recomputed on wanted create/update, on
-- listing publish/update, and by a periodic job. Formula: DATA_MODEL.md §7.
CREATE TABLE IF NOT EXISTS matches (
  id              TEXT PRIMARY KEY,
  wanted_id       TEXT NOT NULL REFERENCES wanted_posts(id) ON DELETE CASCADE,
  listing_id      TEXT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  score           INTEGER NOT NULL CHECK (score BETWEEN 0 AND 100),
  breakdown_json  TEXT NOT NULL DEFAULT '{}' CHECK (json_valid(breakdown_json)),  -- {price:30,dates:25,location:20,...}
  status          TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new','seen','dismissed','offered','contacted')),
  offered_by_host INTEGER NOT NULL DEFAULT 0 CHECK (offered_by_host IN (0,1)),
  conversation_id TEXT REFERENCES conversations(id) ON DELETE SET NULL,
  computed_at     TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at      TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  UNIQUE (wanted_id, listing_id)
);
CREATE INDEX IF NOT EXISTS idx_matches_wanted_score ON matches(wanted_id, status, score DESC);
CREATE INDEX IF NOT EXISTS idx_matches_listing_score ON matches(listing_id, status, score DESC);

